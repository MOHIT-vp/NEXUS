"""
Interview Agent (A5) — mock-interview practice plan + personalised learning roadmap.

Architecture contract:
- Input: skill-gap report, coding analytics, specialist analysis, retrieved resources,
  the student's clarified timeline and priorities
- Output: practice questions (domain question banks + gap-targeted), a mock-interview
  session plan, and a roadmap whose items cite the gap and the retrieved resource
- Guardrails: mark all AI output clearly; keep session recordings private (none are
  stored here); faculty sign-off is required before readiness certification
"""
from datetime import datetime, timezone
