logger = logging.getLogger(__name__)

PRIORITY_WEIGHTS = {"critical": 4, "high": 3, "medium": 2, "low": 1}
SEVERITY_TO_PRIORITY = {"critical": "critical", "high": "high", "medium": "medium", "low": "low", "none": "low"}
HOURS_BY_SEVERITY = {"critical": 30, "high": 20, "medium": 12, "low": 6}

AI_DISCLAIMER = ("[AI-Generated] Practice questions, evaluations and roadmap items are generated by the system. "
                 "Faculty sign-off is required for readiness certification.")


def _compute_interview_readiness_score(
    skill_gap_report: Optional[Dict[str, Any]],
    coding_analytics: Optional[Dict[str, Any]],
) -> Dict[str, Any]:
    """
    Pre-assessment of how prepared the student is likely to be (not actual performance).
    Components without data are excluded rather than assigned a neutral guess.
    """
    components = []
    if skill_gap_report and skill_gap_report.get("per_role", True):
        coverage = skill_gap_report.get("overall_coverage", 0) or 0
        components.append(("skill_readiness", round(min(coverage / 100, 1.0) * 30, 2), 30))
    summary = (coding_analytics or {}).get("summary") or {}
    index = summary.get("coding_index", summary.get("coding_percentile"))
    if index is not None:
        components.append(("coding_practice", round(min(index / 100, 1.0) * 40, 2), 40))
        topics = (coding_analytics or {}).get("topic_analysis", [])
        if topics:
            strong = sum(1 for t in topics if t.get("strength_level") in ("strong", "competent"))
            components.append(("topic_diversity", round(strong / max(len(topics), 1) * 30, 2), 30))
    total = sum(c[1] for c in components)
    max_total = sum(c[2] for c in components)
    return {
        "readiness_score": round(total, 2),
        "max_score": max_total,
        "percentage": round(total / max_total * 100, 1) if max_total else 0.0,
        "components": [{"name": n, "score": s, "max": m} for n, s, m in components],
        "excluded": [n for n in ("skill_readiness", "coding_practice", "topic_diversity")
                     if n not in [c[0] for c in components]],
    }


def _determine_question_focus(skill_gap_report: Optional[Dict[str, Any]]) -> List[Dict[str, Any]]:
    focus = []
    for gap in (skill_gap_report or {}).get("gaps", []):
        focus.append({
            "skill": gap.get("skill", "General"),
            "current_level": gap.get("current_level", "unknown"),
            "required_level": gap.get("required_level", "intermediate"),
            "severity": gap.get("severity", "medium"),
            "importance": gap.get("importance", "required"),
            "priority": SEVERITY_TO_PRIORITY.get(gap.get("severity", "medium"), "medium"),
        })
    for s in (skill_gap_report or {}).get("strengths", [])[:2]:
        focus.append({"skill": s.get("skill", "General"), "current_level": s.get("level", "intermediate"),
                      "required_level": s.get("level", "intermediate"), "severity": "none",
                      "importance": s.get("importance", "required"), "priority": "low"})
    focus.sort(key=lambda x: (PRIORITY_WEIGHTS.get(x["priority"], 1), x.get("importance") == "required"), reverse=True)
    return focus


def _sort_roadmap_by_priority(items: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    return sorted(items, key=lambda x: PRIORITY_WEIGHTS.get(x.get("priority", "low"), 1), reverse=True)


def _weeks_from_timeline(timeline: Optional[str]) -> Optional[int]:
    if not timeline:
        return None
    t = str(timeline).lower()
    m = re.search(r"(\d+)\s*(week|month)", t)
    if m:
        n = int(m.group(1))
        return n * 4 if m.group(2).startswith("month") else n
    return None


def _questions(focus: List[Dict[str, Any]], specialist: Dict[str, Any]) -> List[Dict[str, Any]]:
    qs: List[Dict[str, Any]] = []
    for area in focus[:6]:
        if area["severity"] == "none":
            text = f"Walk me through a project where you used {area['skill']}. What trade-offs did you make?"
            difficulty, qtype = "medium", "technical"
        else:
            text = (f"Explain the core concepts of {area['skill']} at a {area['required_level']} level "
                    f"and describe how you would apply them in a real task.")
            difficulty = "hard" if area["required_level"] == "advanced" else "medium"
            qtype = "technical"
        qs.append({
            "text": text, "type": qtype, "difficulty": difficulty, "skill_targeted": area["skill"],
            "source": "gap_targeted",
            "expected_answer_outline": f"Demonstrates {area['required_level']}-level understanding of {area['skill']} with a concrete example.",
            "scoring_rubric": f"Accuracy of {area['skill']} concepts, depth, and practical application.",
            "ai_generated": True,
        })
    for spec in specialist.get("specialists", []):
        for q in spec.get("interview_focus", [])[:4]:
            qs.append({
                "text": q, "type": "domain", "difficulty": "medium", "skill_targeted": spec["name"],
                "source": f"domain_pack:{spec['domain']}",
                "expected_answer_outline": f"Domain-appropriate answer for {spec['name']} interviews.",
                "scoring_rubric": "Correctness, structure, and use of examples.",
                "ai_generated": False,
            })
    qs.append({
        "text": "Tell me about a time you had to learn a new skill quickly to finish a project.",
        "type": "behavioral", "difficulty": "easy", "skill_targeted": "Learning agility", "source": "standard_behavioral",
        "expected_answer_outline": "STAR format: situation, task, action, measurable result.",
        "scoring_rubric": "Clarity, ownership, reflection.", "ai_generated": False,
    })
    return qs


def _roadmap(focus: List[Dict[str, Any]], resources: Dict[str, List[Dict[str, Any]]],
             specialist: Dict[str, Any], priorities: List[str]) -> List[Dict[str, Any]]:
    prio_keys = {canonical(p) for p in priorities or []}
    items: List[Dict[str, Any]] = []
    for area in focus:
        if area["severity"] == "none":
            continue
        key = canonical(area["skill"])
        res = resources.get(key, [])
        priority = area["priority"]
        if key in prio_keys and priority in ("medium", "low"):
            priority = "high"
        items.append({
            "skill": area["skill"],
            "title": f"Reach {area['required_level']} level in {area['skill']}",
            "description": (f"Gap: current {area['current_level']}, required {area['required_level']} "
                            f"({area['importance']}). Study the resource below, then apply {area['skill']} in a project."),
            "priority": priority,
            "resources": [{"title": r["title"], "url": r.get("url"), "source": r["source"]} for r in res[:2]],
            "resource_status": "cited" if res else "no_resource_in_knowledge_base",
            "estimated_hours": HOURS_BY_SEVERITY.get(area["severity"], 10),
            "milestone": f"A project or certificate that demonstrates {area['required_level']} {area['skill']}",
            "addresses_gap": area["skill"],
            "student_priority": key in prio_keys,
            "ai_generated": True,
        })
    for spec in specialist.get("specialists", []):
        for rec in spec.get("recommendations", [])[:2]:
            items.append({
                "skill": spec["name"],
                "title": rec["title"],
                "description": rec["detail"],
                "priority": rec["priority"],
                "resources": [],
                "resource_status": "domain_specialist",
                "estimated_hours": 8,
                "milestone": rec["title"],
                "addresses_gap": ", ".join(rec["references"][:3]),
                "source": f"domain_pack:{spec['domain']}",
                "ai_generated": True,
            })
    return _sort_roadmap_by_priority(items)


def _mock_plan(focus: List[Dict[str, Any]], weeks: Optional[int], specialist: Dict[str, Any]) -> Dict[str, Any]:
    sessions = max(2, min(8, (weeks or 8) // 2))
    gap_skills = [f["skill"] for f in focus if f["severity"] != "none"][:sessions]
    domains = [s["name"] for s in specialist.get("specialists", [])]
    plan = []
    for i in range(sessions):
        skill = gap_skills[i % len(gap_skills)] if gap_skills else (domains[0] if domains else "Fundamentals")
        plan.append({
            "session": i + 1,
            "week": (i * 2) + 1,
            "type": "technical" if i % 3 != 2 else "behavioral",
            "focus": skill,
            "format": "Faculty- or peer-led mock interview (45 min) with written feedback",
        })
    return {"sessions": plan, "total_sessions": sessions,
            "timeline_weeks": weeks, "note": "Recordings are not stored by the portal; feedback is entered by the reviewer."}


def interview_agent_node(state: PlacementState) -> Dict[str, Any]:
    """LangGraph node: Interview Agent."""
    profile = state.get("student_profile")
    if not profile:
        return {"errors": ["InterviewAgent: No student profile available."], "current_step": "interview_agent"}

    gap_report = state.get("skill_gap_report")
    coding = state.get("coding_analytics")
    specialist = state.get("specialist_analysis") or {}
    retrieval = dict(state.get("retrieval") or {})
    prefs = (state.get("student_context") or {}).get("career_preferences") or {}
    request = state.get("request_context") or {}
    timeline = request.get("timeline") if isinstance(request, dict) else None
    timeline = timeline or prefs.get("timeline")
    priorities = (request.get("priorities") if isinstance(request, dict) else None) or prefs.get("priorities") or []

    readiness = _compute_interview_readiness_score(gap_report, coding)
    focus = _determine_question_focus(gap_report)
    resources = dict(retrieval.get("learning_resources") or {})

    # Retrieve resources for gaps the skill-gap stage did not cover (e.g. after self-healing)
    try:
        hub = get_hub(state)
        for area in focus:
            key = canonical(area["skill"])
            if area["severity"] != "none" and key not in resources:
                res = hub.retrieve(f"{display_name(key)} learning resource", doc_types=["learning_resource"], k=2)
                hits = [i.model_dump() for i in res.items if key in [canonical(t) for t in i.tags]]
                if hits:
                    resources[key] = hits
    except HubUnavailableError:
        pass

    questions = _questions(focus, specialist)
    weeks = _weeks_from_timeline(timeline)
    # Lab 8: build several roadmap candidates in parallel and keep the one that best fits the locked plan
    from app.agents.roadmap_selector import select_best_roadmap
    chosen = select_best_roadmap(_roadmap(focus, resources, specialist, priorities),
                                 (gap_report or {}).get("gaps", []), priorities, weeks)
    roadmap_items = chosen["items"]
    mock_plan = _mock_plan(focus, weeks, specialist)

    tips = []
    if focus and focus[0]["severity"] != "none":
        tips.append(f"Start with {focus[0]['skill']} — it is your highest-priority gap.")
    if weeks:
        total_hours = sum(i["estimated_hours"] for i in roadmap_items)
        tips.append(f"Your roadmap totals about {total_hours} hours; over {weeks} weeks that is ~{round(total_hours / weeks, 1)} hours/week.")
    tips.append("Prepare STAR-format answers for behavioural questions.")

    llm = get_chat_model(temperature=0.4, agent_name="interview_agent")
    narration_method = "deterministic"
    if llm is not None and focus:
        try:
            from langchain_core.messages import HumanMessage, SystemMessage
            msg = llm.invoke([
                SystemMessage(content="Write 2 additional interview practice questions, one per line, targeting only these skills. "
                                      "No numbering, no answers."),
                HumanMessage(content=", ".join(f["skill"] for f in focus[:4])),
            ])
            text = getattr(msg, "content", "")
            if isinstance(text, str):
                for line in [l.strip("-• ").strip() for l in text.splitlines() if l.strip()][:2]:
                    questions.append({"text": line[:300], "type": "technical", "difficulty": "medium",
                                      "skill_targeted": focus[0]["skill"], "source": "llm",
                                      "expected_answer_outline": "", "scoring_rubric": "", "ai_generated": True})
                narration_method = "llm"
        except Exception as exc:
            logger.warning(f"[InterviewAgent] LLM questions unavailable: {exc}")

    target_role = (gap_report or {}).get("target_roles", [None])[0] if gap_report else None
    total_hours = sum(i.get("estimated_hours", 0) for i in roadmap_items)
    interview_result = {
        "target_role": target_role,
        "readiness_assessment": readiness,
        "questions": questions,
        "total_questions": len(questions),
        "mock_interview_plan": mock_plan,
        "mock_evaluation": {
            "status": "not_started",
            "note": "Mock interviews are evaluated by faculty/peers; no score is assumed in advance.",
            "ai_generated_disclaimer": AI_DISCLAIMER,
        },
        "preparation_tips": tips,
        "ai_generated_disclaimer": AI_DISCLAIMER,
        "narration_method": narration_method,
        "computed_at": datetime.now(timezone.utc).isoformat(),
    }
    roadmap = {
        "items": roadmap_items,
        "total_items": len(roadmap_items),
        "total_estimated_hours": total_hours,
        "timeline": timeline,
        "timeline_weeks": weeks,
        "focus_summary": (f"{len([i for i in roadmap_items if i['priority'] in ('critical', 'high')])} high-priority items, "
                          f"{total_hours} total estimated hours"),
        "ai_generated_disclaimer": AI_DISCLAIMER,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "selection": chosen["selection"],
    }
    retrieval["learning_resources"] = resources
    retrieval["roadmap_citations"] = sorted({r["url"] for i in roadmap_items for r in i["resources"] if r.get("url")})

    evidence = [EvidenceRecord(
        entity_type="interview_preparation", evidence_type="plan_generation", source="interview_agent + domain packs",
        content=f"{len(questions)} practice questions, {mock_plan['total_sessions']} mock sessions, "
                f"{len(roadmap_items)} roadmap items ({len(retrieval['roadmap_citations'])} cited resources).",
        scope_tags=["interview", "roadmap"],
    ).model_dump()]
    audit = AuditEvent(action="interview_prepared", agent="InterviewAgent", timestamp=datetime.now(timezone.utc).isoformat(),
                       details={"questions": len(questions), "roadmap_items": len(roadmap_items),
                                "roadmap_selected": chosen["selection"]["selected"],
                                "roadmap_candidates": {c["strategy"]: c["score"] for c in chosen["selection"]["candidates"]},
                                "readiness_pct": readiness["percentage"], "timeline_weeks": weeks})
    return {"interview_result": interview_result, "roadmap": roadmap, "retrieval": retrieval,
            "evidence_records": evidence, "audit_events": [audit], "current_step": "interview_agent"}
