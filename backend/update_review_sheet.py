def set_cell_formatted_runs(cell, runs_data, font_name="Calibri", font_size=114300, space_before=25400, space_after=25400):
    """
    Sets formatted runs in cell, preserving exact paragraph format and font styling.
    runs_data: list of tuples (text, is_bold)
    """
    # Remove any extra paragraphs if present
    for i in range(len(cell.paragraphs) - 1, 0, -1):
        p_elem = cell.paragraphs[i]._p
        p_elem.getparent().remove(p_elem)
        
    p = cell.paragraphs[0]
    p.text = ""
    # remove all runs generated by setting p.text = ""
    for r in list(p.runs):
        r._r.getparent().remove(r._r)
        
    p.paragraph_format.space_before = space_before
    p.paragraph_format.space_after = space_after
    p.paragraph_format.line_spacing = None
    
    for text, bold in runs_data:
        r = p.add_run(text)
        r.bold = bold
        r.font.name = font_name
        r.font.size = font_size

